"""Write packaging/version_info.txt (Windows VERSIONINFO resource) from n1mm_timer.__version__.

Executables without publisher/product metadata look anonymous to antivirus heuristics and
SmartScreen; this embeds proper File/Product version, company and description fields.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from n1mm_timer import __version__  # noqa: E402

COMPANY = "S55OO"
PRODUCT = "N1MM_timer"
DESCRIPTION = "N1MM_timer - band-change rule watcher for N1MM Logger+"
COPYRIGHT = "(c) 2026 S55OO - MIT License"

TEMPLATE = """# generated by packaging/make_version_file.py, do not edit
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vt}, prodvers={vt},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', '{company}'),
        StringStruct('FileDescription', '{desc}'),
        StringStruct('FileVersion', '{v}'),
        StringStruct('InternalName', '{product}'),
        StringStruct('LegalCopyright', '{copy}'),
        StringStruct('OriginalFilename', '{product}.exe'),
        StringStruct('ProductName', '{product}'),
        StringStruct('ProductVersion', '{v}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def version_tuple(v: str):
    nums = [int(x) for x in re.findall(r"\d+", v)[:4]]
    return tuple(nums + [0] * (4 - len(nums)))


def main():
    if "--print-version" in sys.argv:
        print(__version__)
        return
    out = os.path.join(ROOT, "packaging", "version_info.txt")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(TEMPLATE.format(vt=version_tuple(__version__), v=__version__, company=COMPANY,
                                 desc=DESCRIPTION, product=PRODUCT, copy=COPYRIGHT))
    print(f"wrote {out} for version {__version__}")


if __name__ == "__main__":
    main()
